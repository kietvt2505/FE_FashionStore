-- Phase 2. Run once in Supabase SQL Editor with the database owner role.
-- No customer, product, invoice or stock records are deleted/rewritten.
-- If existing emails/phones are duplicated, abort and review with the team.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
DO $$
BEGIN
    IF to_regclass('public.khachhang') IS NULL OR to_regclass('public.sanpham') IS NULL THEN
        RAISE EXCEPTION 'Required shared customer/product tables are missing';
    END IF;
    IF EXISTS (SELECT 1 FROM public.khachhang WHERE email IS NOT NULL AND btrim(email) <> ''
               GROUP BY lower(btrim(email)) HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Duplicate customer emails: review existing data before applying this migration';
    END IF;
END $$;

ALTER TABLE public.khachhang ADD COLUMN IF NOT EXISTS nhankhuyenmai boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX IF NOT EXISTS ux_web_customer_email ON public.khachhang(lower(btrim(email)))
    WHERE email IS NOT NULL AND btrim(email) <> '';
CREATE UNIQUE INDEX IF NOT EXISTS ux_web_customer_phone ON public.khachhang(sodienthoai);

-- Website additions share the partner public schema.
-- Keep the existing public schema privileges unchanged.
CREATE TABLE IF NOT EXISTS public.customer_account (
    makh varchar(20) PRIMARY KEY REFERENCES public.khachhang(makh) ON DELETE RESTRICT,
    tendangnhap varchar(100) NOT NULL UNIQUE CHECK (tendangnhap = lower(btrim(tendangnhap))),
    matkhauhash varchar(500) NOT NULL,
    trangthai boolean NOT NULL DEFAULT true,
    ngaytao timestamp without time zone NOT NULL,
    dangnhapcuoi timestamp without time zone NULL
);
CREATE TABLE IF NOT EXISTS public.cart (
    magiohang bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makh varchar(20) NOT NULL UNIQUE REFERENCES public.khachhang(makh) ON DELETE RESTRICT,
    ngaytao timestamp without time zone NOT NULL,
    ngaycapnhat timestamp without time zone NOT NULL
);
CREATE TABLE IF NOT EXISTS public.cart_line (
    magiohang bigint NOT NULL REFERENCES public.cart(magiohang) ON DELETE CASCADE,
    masku varchar(40) NOT NULL REFERENCES public.sanpham(masku) ON DELETE RESTRICT,
    soluong integer NOT NULL CHECK (soluong > 0),
    ngaycapnhat timestamp without time zone NOT NULL,
    PRIMARY KEY (magiohang, masku)
);
ALTER TABLE public.customer_account ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cart ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cart_line ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.customer_account,public.cart,public.cart_line FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.cart_magiohang_seq FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN

        REVOKE ALL ON TABLE public.customer_account,public.cart,public.cart_line FROM anon;
        REVOKE ALL ON SEQUENCE public.cart_magiohang_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN

        REVOKE ALL ON TABLE public.customer_account,public.cart,public.cart_line FROM authenticated;
        REVOKE ALL ON SEQUENCE public.cart_magiohang_seq FROM authenticated;
    END IF;
END $$;
COMMIT;
