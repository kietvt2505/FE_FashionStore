using Npgsql;
using Xunit;

namespace FashionStore.Backend.Tests;

public sealed class PublicSchemaMigrationTests
{
    [PostgresLocalFact]
    public async Task MovePreservesDataDependenciesIdentityPrivacyAndSupportsRollback()
    {
        var settings=new NpgsqlConnectionStringBuilder(Environment.GetEnvironmentVariable("FASHIONSTORE_POSTGRES_TEST_CONNECTION")!);
        Assert.Contains(settings.Host,new[]{"127.0.0.1","localhost","::1"});
        Assert.Equal("fashionstore_test",settings.Database);
        var testDatabase="fashionstore_schema_"+Guid.NewGuid().ToString("N");
        settings.Database="postgres";
        await using var admin=new NpgsqlConnection(settings.ConnectionString);await admin.OpenAsync();
        await using(var create=new NpgsqlCommand($"CREATE DATABASE {testDatabase}",admin))await create.ExecuteNonQueryAsync();
        try
        {
            settings.Database=testDatabase;
            await using var sql=new NpgsqlConnection(settings.ConnectionString);await sql.OpenAsync();
            async Task Exec(string command){await using var cmd=new NpgsqlCommand(command,sql){CommandTimeout=120};await cmd.ExecuteNonQueryAsync();}
            async Task<T> Value<T>(string command){await using var cmd=new NpgsqlCommand(command,sql);return (T)(await cmd.ExecuteScalarAsync())!;}
            await Exec("""
                CREATE TABLE public.khachhang(makh text PRIMARY KEY);
                CREATE TABLE public.sanpham(masku text PRIMARY KEY);
                CREATE TABLE public.hoadon(sohd text PRIMARY KEY,status text);
                CREATE SCHEMA webstore;
                REVOKE ALL ON SCHEMA webstore FROM PUBLIC;
                CREATE TYPE webstore.request_kind AS ENUM('TRA','DOI');
                CREATE TABLE webstore.customer_account(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,makh text REFERENCES public.khachhang,hash text);
                CREATE TABLE webstore.order_snapshot(sohd text PRIMARY KEY REFERENCES public.hoadon,makh text REFERENCES public.khachhang);
                CREATE TABLE webstore.return_request(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,sohd text REFERENCES webstore.order_snapshot,kind webstore.request_kind,reason text);
                ALTER TABLE webstore.customer_account ENABLE ROW LEVEL SECURITY;
                ALTER TABLE webstore.return_request ENABLE ROW LEVEL SECURITY;
                ALTER TABLE webstore.return_request FORCE ROW LEVEL SECURITY;
                CREATE SEQUENCE webstore.web_order_number START WITH 100;
                CREATE VIEW webstore.return_list AS SELECT * FROM webstore.return_request;
                CREATE MATERIALIZED VIEW webstore.return_count AS SELECT count(*) FROM webstore.return_request;
                CREATE VIEW public.partner_returns AS SELECT id,reason FROM webstore.return_request;
                INSERT INTO public.khachhang VALUES('KH1');INSERT INTO public.sanpham VALUES('SKU1');
                INSERT INTO public.hoadon VALUES('HD1','MOI');
                INSERT INTO webstore.customer_account(makh,hash) VALUES('KH1','synthetic-hash');
                INSERT INTO webstore.order_snapshot VALUES('HD1','KH1');
                INSERT INTO webstore.return_request(sohd,kind,reason) VALUES('HD1','TRA','Giữ nguyên nội dung');
                SELECT setval('webstore.web_order_number',123);
                CREATE FUNCTION webstore.pending_count() RETURNS bigint LANGUAGE sql SET search_path=pg_catalog,webstore AS $$ SELECT count(*) FROM webstore.return_request $$;
                CREATE FUNCTION webstore.new_number() RETURNS bigint LANGUAGE sql AS $$ SELECT nextval('webstore.web_order_number') $$;
                CREATE FUNCTION public.partner_count() RETURNS bigint LANGUAGE sql AS $$ SELECT webstore.pending_count() $$;
                CREATE FUNCTION webstore.guard_order() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN PERFORM webstore.pending_count(); RETURN NEW; END $$;
                CREATE TRIGGER website_guard BEFORE UPDATE ON public.hoadon FOR EACH ROW EXECUTE FUNCTION webstore.guard_order();
                """);
            var originalOid=await Value<uint>("SELECT 'webstore.return_request'::regclass::oid");
            var originalFunction=await Value<uint>("SELECT 'webstore.pending_count()'::regprocedure::oid");
            var migrate=await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory,"Supabase-Move-Webstore-To-Public.sql"));
            var rollback=await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory,"Supabase-Move-Webstore-To-Public-Rollback.sql"));
            // A collision must roll back EVERYTHING; no partial move and no leaked journal.
            await Exec("CREATE TABLE public.return_request(id int)");
            await Assert.ThrowsAsync<PostgresException>(()=>Exec(migrate));await Exec("ROLLBACK");
            Assert.True(await Value<bool>("SELECT to_regclass('webstore.return_request') IS NOT NULL AND to_regclass('public.web_schema_migration_20261102') IS NULL"));
            await Exec("DROP TABLE public.return_request");
            await Exec(migrate);
            Assert.True(await Value<bool>("SELECT to_regnamespace('webstore') IS NULL"));
            Assert.Equal(originalOid,await Value<uint>("SELECT 'public.return_request'::regclass::oid"));
            Assert.Equal(originalFunction,await Value<uint>("SELECT 'public.pending_count()'::regprocedure::oid"));
            Assert.Equal("Giữ nguyên nội dung",await Value<string>("SELECT reason FROM public.return_request"));
            Assert.Equal(1L,await Value<long>("SELECT public.pending_count()"));
            Assert.Equal(1L,await Value<long>("SELECT public.partner_count()"));
            Assert.Equal(124L,await Value<long>("SELECT public.new_number()"));
            Assert.Equal(1L,await Value<long>("SELECT count(*) FROM public.partner_returns"));
            Assert.True(await Value<bool>("SELECT relrowsecurity AND relforcerowsecurity FROM pg_class WHERE oid='public.return_request'::regclass"));
            Assert.False(await Value<bool>("SELECT EXISTS(SELECT 1 FROM pg_proc p,LATERAL aclexplode(COALESCE(p.proacl,acldefault('f',p.proowner))) a WHERE p.oid='public.pending_count()'::regprocedure AND a.grantee=0 AND a.privilege_type='EXECUTE')"));
            await Exec("UPDATE public.hoadon SET status='XAC_NHAN';INSERT INTO public.return_request(sohd,kind,reason) VALUES('HD1','DOI','Sau khi chuyển')");
            Assert.Equal(2L,await Value<long>("SELECT max(id) FROM public.return_request"));
            await Exec(migrate); // No destructive work on a second run.
            await Exec(rollback);
            Assert.Equal(originalOid,await Value<uint>("SELECT 'webstore.return_request'::regclass::oid"));
            Assert.Equal(2L,await Value<long>("SELECT public.partner_count()"));
            Assert.Equal(125L,await Value<long>("SELECT webstore.new_number()"));
            Assert.Equal(2L,await Value<long>("SELECT count(*) FROM public.partner_returns"));
            Assert.Equal("synthetic-hash",await Value<string>("SELECT hash FROM webstore.customer_account"));
            await Exec("UPDATE public.hoadon SET status='MOI'");
        }
        finally
        {
            await using var drop=new NpgsqlCommand($"DROP DATABASE {testDatabase} WITH (FORCE)",admin);await drop.ExecuteNonQueryAsync();
        }
    }
}
