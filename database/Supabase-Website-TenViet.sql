CREATE OR REPLACE FUNCTION public.merge_guest_cart(p_customer varchar,p_request uuid,p_lines jsonb)
RETURNS text LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE giohang_id bigint; line record; existing_qty integer; available integer; active boolean; BEGIN
    IF p_request IS NULL OR p_request='00000000-0000-0000-0000-000000000000'::uuid OR p_lines IS NULL
       OR jsonb_typeof(p_lines)<>'array' THEN RAISE EXCEPTION 'Invalid guest cart'; END IF;
    IF jsonb_array_length(p_lines) NOT BETWEEN 1 AND 50 THEN RAISE EXCEPTION 'Invalid guest cart'; END IF;
    IF EXISTS(SELECT 1 FROM jsonb_to_recordset(p_lines) AS x(sku text,quantity integer)
        WHERE sku IS NULL OR btrim(sku)='' OR length(sku)>40 OR quantity IS NULL OR quantity<1)
        THEN RAISE EXCEPTION 'Invalid quantity or SKU'; END IF;
    PERFORM 1 FROM public.khachhang WHERE makh=p_customer AND trangthai FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Inactive customer'; END IF;
    INSERT INTO public.lichsugopgiohang(makh,request_id) VALUES(p_customer,p_request) ON CONFLICT DO NOTHING;
    IF NOT FOUND THEN RETURN 'ALREADY_APPLIED'; END IF;
    INSERT INTO public.giohang(makh,ngaytao,ngaycapnhat) VALUES(p_customer,CURRENT_TIMESTAMP AT TIME ZONE 'UTC',CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    ON CONFLICT(makh) DO UPDATE SET ngaycapnhat=EXCLUDED.ngaycapnhat RETURNING magiohang INTO giohang_id;
    FOR line IN SELECT sku,sum(quantity)::bigint AS quantity FROM jsonb_to_recordset(p_lines) AS x(sku text,quantity integer) GROUP BY sku ORDER BY sku LOOP
        IF line.sku IS NULL OR length(line.sku)>40 OR line.quantity IS NULL OR line.quantity<1 OR line.quantity>2147483647 THEN RAISE EXCEPTION 'Invalid quantity or SKU'; END IF;
        SELECT p.soluongtonkho,p.trangthai AND c.trangthai AND btrim(p.tensanpham)<>'123' AND btrim(c.tenloai)<>'123'
        INTO available,active FROM public.sanpham p JOIN public.loaisanpham c USING(maloai) WHERE masku=line.sku FOR SHARE OF p,c;
        IF NOT FOUND OR NOT active THEN RAISE EXCEPTION 'Product is unavailable'; END IF;
        SELECT soluong INTO existing_qty FROM public.chitietgiohang WHERE magiohang=giohang_id AND masku=line.sku;
        IF COALESCE(existing_qty,0)::bigint+line.quantity>available THEN RAISE EXCEPTION 'Quantity exceeds stock'; END IF;
        INSERT INTO public.chitietgiohang(magiohang,masku,soluong,ngaycapnhat)
        VALUES(giohang_id,line.sku,COALESCE(existing_qty,0)+line.quantity,CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
        ON CONFLICT(magiohang,masku) DO UPDATE SET soluong=EXCLUDED.soluong,ngaycapnhat=EXCLUDED.ngaycapnhat;
    END LOOP;
    RETURN 'APPLIED';
END $$;

