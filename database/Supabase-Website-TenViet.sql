CREATE OR REPLACE FUNCTION public.capture_cancelled_order_payment()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
BEGIN
    IF NEW.loaihoadon='WEB_HUY' AND NEW.trangthaithanhtoan='DA_THANH_TOAN'
       AND OLD.trangthaithanhtoan IS DISTINCT FROM 'DA_THANH_TOAN' AND NEW.tienkhachdua>0
       AND EXISTS(SELECT 1 FROM public.lichsuhuydonhang WHERE sohd=NEW.sohd AND makh=NEW.makh)
       AND EXISTS(SELECT 1 FROM public.biennhanthanhtoantructuyen r JOIN public.yeucauthanhtoantructuyen a ON a.id=r.attempt_id
           WHERE a.sohd=NEW.sohd AND r.outcome='REVIEW' AND r.amount=NEW.tienkhachdua) THEN
        INSERT INTO public.yeucauhoantien(sohd,makh,amount,status)
        VALUES(NEW.sohd,NEW.makh,NEW.tienkhachdua,'CHO_THONG_TIN') ON CONFLICT(sohd) DO NOTHING;
    END IF;
    RETURN NEW;
END $$;
