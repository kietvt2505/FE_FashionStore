-- After Supabase-Customer-Cart.sql and Supabase-Web-Orders.sql.
-- Adds customer-owned website data. No stock, points or refund is changed by this migration.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='60s';
DO $$ BEGIN
    IF to_regclass('public.khachhang') IS NULL OR to_regclass('public.thongtindonhang') IS NULL THEN
        RAISE EXCEPTION 'Apply customer/cart and web order migrations first';
    END IF;
    PERFORM paymentmethod FROM public.thongtindonhang LIMIT 0;
    PERFORM ngaygiaothanhcong,trangthaigiaohang,trangthaithanhtoan FROM public.hoadon LIMIT 0;
    PERFORM sohd,sophieudt,trangthai FROM public.phieudoitra LIMIT 0;
    PERFORM sophieudt,masku,soluong FROM public.chitietdoitra LIMIT 0;
END $$;
CREATE TABLE IF NOT EXISTS public.diachikhachhang (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makh varchar(20) NOT NULL REFERENCES public.khachhang(makh),
    recipient varchar(150) NOT NULL, phone varchar(20) NOT NULL, address varchar(300) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_web_diachikhachhang_owner ON public.diachikhachhang(makh,id DESC);
CREATE TABLE IF NOT EXISTS public.sanphamyeuthich (
    makh varchar(20) NOT NULL REFERENCES public.khachhang(makh), masp varchar(20) NOT NULL,
    createdat timestamp without time zone NOT NULL DEFAULT LOCALTIMESTAMP, PRIMARY KEY(makh,masp)
);
CREATE TABLE IF NOT EXISTS public.danhgiasanpham (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makh varchar(20) NOT NULL REFERENCES public.khachhang(makh), masp varchar(20) NOT NULL,
    sohd varchar(30) NOT NULL REFERENCES public.thongtindonhang(sohd), stars integer NOT NULL CHECK(stars BETWEEN 1 AND 5),
    body varchar(2000) NOT NULL, createdat timestamp without time zone NOT NULL DEFAULT LOCALTIMESTAMP,
    status varchar(20) NOT NULL DEFAULT 'HIEN_THI' CHECK(status IN ('CHO_DUYET','HIEN_THI','TU_CHOI')),
    UNIQUE(makh,masp,sohd)
);
CREATE INDEX IF NOT EXISTS ix_web_review_product ON public.danhgiasanpham(masp,status,createdat DESC,id DESC);
CREATE TABLE IF NOT EXISTS public.yeucaudoitra (
    sophieudt varchar(30) PRIMARY KEY,
    sohd varchar(30) NOT NULL REFERENCES public.thongtindonhang(sohd), makh varchar(20) NOT NULL REFERENCES public.khachhang(makh),
    masku varchar(40) NOT NULL, quantity integer NOT NULL CHECK(quantity>0),
    kind varchar(10) NOT NULL CHECK(kind IN ('DOI','TRA')), newsku varchar(40), reason varchar(500) NOT NULL,
    createdat timestamp without time zone NOT NULL DEFAULT LOCALTIMESTAMP,
    status varchar(20) NOT NULL DEFAULT 'CHO_DUYET' CHECK(status IN ('CHO_DUYET','DA_DUYET','HOAN_TAT','TU_CHOI')),
    rejectionreason varchar(500), handled_return_id varchar(30)
);
CREATE INDEX IF NOT EXISTS ix_web_return_owner ON public.yeucaudoitra(makh,createdat DESC);
CREATE INDEX IF NOT EXISTS ix_web_return_order ON public.yeucaudoitra(sohd,masku,status);
CREATE TABLE IF NOT EXISTS public.yeucaukhoiphucmatkhau (
    tokenhash varchar(64) PRIMARY KEY, makh varchar(20) NOT NULL REFERENCES public.khachhang(makh),
    passwordversion varchar(64) NOT NULL, expiresatutc timestamp with time zone NOT NULL,
    usedatutc timestamp with time zone
);
CREATE INDEX IF NOT EXISTS ix_web_reset_owner ON public.yeucaukhoiphucmatkhau(makh);
DO $$ DECLARE tab text; BEGIN
    FOREACH tab IN ARRAY ARRAY['diachikhachhang','sanphamyeuthich','danhgiasanpham','yeucaudoitra','yeucaukhoiphucmatkhau'] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',tab);
        EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC',tab);
        IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='anon') THEN EXECUTE format('REVOKE ALL ON public.%I FROM anon',tab); END IF;
        IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN EXECUTE format('REVOKE ALL ON public.%I FROM authenticated',tab); END IF;
    END LOOP;
END $$;
REVOKE ALL ON SEQUENCE public.diachikhachhang_id_seq,public.danhgiasanpham_id_seq FROM PUBLIC;
COMMIT;
