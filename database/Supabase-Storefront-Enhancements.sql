BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='60s';
ALTER TABLE webstore.catalog_product ADD COLUMN IF NOT EXISTS description text;
CREATE TABLE IF NOT EXISTS webstore.product_media(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    masp varchar(20) NOT NULL,color varchar(60),url text NOT NULL CHECK(url ~ '^https://'),
    alt varchar(200),sort_order integer NOT NULL DEFAULT 0,active boolean NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS ix_product_media_product ON webstore.product_media(masp,sort_order,id);
CREATE TABLE IF NOT EXISTS webstore.product_discount_price(
    masku varchar(40) PRIMARY KEY REFERENCES public.sanpham(masku),
    masp varchar(20) NOT NULL,base_price numeric(18,2) NOT NULL CHECK(base_price>0),
    percent numeric(5,2) NOT NULL CHECK(percent>=0 AND percent<100)
);
CREATE OR REPLACE FUNCTION webstore.set_product_discount(p_product varchar,p_percent numeric)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE r record; original numeric; old_price record; BEGIN
    IF p_percent IS NULL OR p_percent<0 OR p_percent>=100 THEN RAISE EXCEPTION 'Discount must be between 0 and less than 100'; END IF;
    PERFORM 1 FROM public.sanpham WHERE masp=p_product ORDER BY masku FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Product does not exist'; END IF;
    FOR r IN SELECT masku,dongia FROM public.sanpham WHERE masp=p_product ORDER BY masku LOOP
        SELECT * INTO old_price FROM webstore.product_discount_price WHERE masku=r.masku;
        original:=r.dongia;
        IF FOUND AND r.dongia=round(old_price.base_price*(100-old_price.percent)/100,0) THEN original:=old_price.base_price; END IF;
        IF round(original*(100-p_percent)/100,0)<=0 THEN RAISE EXCEPTION 'Discount creates a zero price'; END IF;
        INSERT INTO webstore.product_discount_price(masku,masp,base_price,percent) VALUES(r.masku,p_product,original,p_percent)
        ON CONFLICT(masku) DO UPDATE SET base_price=EXCLUDED.base_price,percent=EXCLUDED.percent;
        UPDATE public.sanpham SET dongia=round(original*(100-p_percent)/100,0) WHERE masku=r.masku;
    END LOOP;
    INSERT INTO webstore.catalog_product(masp,regular_price)
    SELECT p_product,CASE WHEN p_percent>0 THEN min(base_price) END FROM webstore.product_discount_price WHERE masp=p_product
    ON CONFLICT(masp) DO UPDATE SET regular_price=EXCLUDED.regular_price;
END $$;

CREATE TABLE IF NOT EXISTS webstore.guest_cart_merge(
    makh varchar(20) NOT NULL REFERENCES public.khachhang(makh),request_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(makh,request_id)
);
CREATE OR REPLACE FUNCTION webstore.merge_guest_cart(p_customer varchar,p_request uuid,p_lines jsonb)
RETURNS text LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE cart_id bigint; line record; existing_qty integer; available integer; active boolean; BEGIN
    IF p_request IS NULL OR p_request='00000000-0000-0000-0000-000000000000'::uuid OR p_lines IS NULL
       OR jsonb_typeof(p_lines)<>'array' THEN RAISE EXCEPTION 'Invalid guest cart'; END IF;
    IF jsonb_array_length(p_lines) NOT BETWEEN 1 AND 50 THEN RAISE EXCEPTION 'Invalid guest cart'; END IF;
    IF EXISTS(SELECT 1 FROM jsonb_to_recordset(p_lines) AS x(sku text,quantity integer)
        WHERE sku IS NULL OR btrim(sku)='' OR length(sku)>40 OR quantity IS NULL OR quantity<1)
        THEN RAISE EXCEPTION 'Invalid quantity or SKU'; END IF;
    PERFORM 1 FROM public.khachhang WHERE makh=p_customer AND trangthai FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Inactive customer'; END IF;
    INSERT INTO webstore.guest_cart_merge(makh,request_id) VALUES(p_customer,p_request) ON CONFLICT DO NOTHING;
    IF NOT FOUND THEN RETURN 'ALREADY_APPLIED'; END IF;
    INSERT INTO webstore.cart(makh,ngaytao,ngaycapnhat) VALUES(p_customer,CURRENT_TIMESTAMP AT TIME ZONE 'UTC',CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    ON CONFLICT(makh) DO UPDATE SET ngaycapnhat=EXCLUDED.ngaycapnhat RETURNING magiohang INTO cart_id;
    FOR line IN SELECT sku,sum(quantity)::bigint AS quantity FROM jsonb_to_recordset(p_lines) AS x(sku text,quantity integer) GROUP BY sku ORDER BY sku LOOP
        IF line.sku IS NULL OR length(line.sku)>40 OR line.quantity IS NULL OR line.quantity<1 OR line.quantity>2147483647 THEN RAISE EXCEPTION 'Invalid quantity or SKU'; END IF;
        SELECT p.soluongtonkho,p.trangthai AND c.trangthai AND btrim(p.tensanpham)<>'123' AND btrim(c.tenloai)<>'123'
        INTO available,active FROM public.sanpham p JOIN public.loaisanpham c USING(maloai) WHERE masku=line.sku FOR SHARE OF p,c;
        IF NOT FOUND OR NOT active THEN RAISE EXCEPTION 'Product is unavailable'; END IF;
        SELECT soluong INTO existing_qty FROM webstore.cart_line WHERE magiohang=cart_id AND masku=line.sku;
        IF COALESCE(existing_qty,0)::bigint+line.quantity>available THEN RAISE EXCEPTION 'Quantity exceeds stock'; END IF;
        INSERT INTO webstore.cart_line(magiohang,masku,soluong,ngaycapnhat)
        VALUES(cart_id,line.sku,COALESCE(existing_qty,0)+line.quantity,CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
        ON CONFLICT(magiohang,masku) DO UPDATE SET soluong=EXCLUDED.soluong,ngaycapnhat=EXCLUDED.ngaycapnhat;
    END LOOP;
    RETURN 'APPLIED';
END $$;
ALTER TABLE webstore.product_media ENABLE ROW LEVEL SECURITY;
ALTER TABLE webstore.product_discount_price ENABLE ROW LEVEL SECURITY;
ALTER TABLE webstore.guest_cart_merge ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON webstore.product_media,webstore.product_discount_price,webstore.guest_cart_merge FROM PUBLIC;
REVOKE ALL ON FUNCTION webstore.set_product_discount(varchar,numeric),webstore.merge_guest_cart(varchar,uuid,jsonb) FROM PUBLIC;
DO $$ DECLARE role_name text; BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
        IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
            EXECUTE format('REVOKE ALL ON webstore.product_media,webstore.product_discount_price,webstore.guest_cart_merge FROM %I',role_name);
            EXECUTE format('REVOKE ALL ON FUNCTION webstore.set_product_discount(varchar,numeric),webstore.merge_guest_cart(varchar,uuid,jsonb) FROM %I',role_name);
        END IF;
    END LOOP;
END $$;
COMMIT;
